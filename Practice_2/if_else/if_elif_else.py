# Determination of age category
age = 25

if age < 13:
    print("Category: Child")
elif age < 20:
    print("Category: Teenager")
elif age < 65:
    print("Category: Adult")
else:
    print("Category: Elderly")

# Exam score
score = 85

if score >= 90:
    print("Grade: A")
elif score >= 80:
    print("Grade: B")
elif score >= 70:
    print("Grade: C")
else:
    print("Grade: D/F")

# Determining the sign of a number
x = 0
if x > 0:
    print("Positive number")
elif x < 0:
    print("Negative number")
else:
    print("Zero")